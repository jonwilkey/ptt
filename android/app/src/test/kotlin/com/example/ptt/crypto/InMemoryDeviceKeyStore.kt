package com.example.ptt.crypto

import com.google.crypto.tink.InsecureSecretKeyAccess
import com.google.crypto.tink.KeysetHandle
import com.google.crypto.tink.hybrid.HpkePrivateKey
import com.google.crypto.tink.hybrid.HpkePublicKey
import com.google.crypto.tink.signature.Ed25519Parameters
import com.google.crypto.tink.signature.Ed25519PrivateKey
import com.google.crypto.tink.signature.Ed25519PublicKey
import com.google.crypto.tink.util.Bytes
import com.google.crypto.tink.util.SecretBytes

/**
 * In-memory keysets for JVM tests (Robolectric has no AndroidKeyStore). Pass handles to use imported
 * key material; anything left null is generated by [create].
 */
class InMemoryDeviceKeyStore(
    private val presetSigning: KeysetHandle? = null,
    private val presetHpke: KeysetHandle? = null
) : DeviceKeyStore {
    private var stored: KeysetPair? = null

    /** When set, [create] fails with it (a Keystore that cannot protect new keys). */
    var failCreate: DeviceKeysUnavailable? = null

    /** The next this-many [load] calls fail, as a transient Keystore error would. */
    var failLoadTimes = 0

    override fun create(): KeysetPair {
        failCreate?.let { throw it }
        check(stored == null) { "device keys already exist" }
        return KeysetPair(
            presetSigning ?: generate(TinkKeys.ed25519Parameters),
            presetHpke ?: generate(TinkKeys.hpkeParameters)
        ).also { stored = it }
    }

    override fun load(): KeysetPair {
        if (failLoadTimes > 0) {
            failLoadTimes--
            throw DeviceKeysUnavailable("transient")
        }
        return stored ?: throw DeviceKeysUnavailable("no keysets")
    }

    override fun wipe() {
        stored = null
    }

    companion object {
        private fun generate(parameters: com.google.crypto.tink.Parameters): KeysetHandle = KeysetHandle.newBuilder()
            .addEntry(KeysetHandle.generateEntryFromParameters(parameters).withRandomId().makePrimary())
            .build()

        /** Imports raw RFC 8032 / RFC 7748 key material, as the vectors carry it. */
        fun ed25519FromSeed(seed: ByteArray, publicKey: ByteArray): KeysetHandle {
            val pub = Ed25519PublicKey.create(Ed25519Parameters.Variant.NO_PREFIX, Bytes.copyFrom(publicKey), null)
            val priv = Ed25519PrivateKey.create(pub, SecretBytes.copyFrom(seed, InsecureSecretKeyAccess.get()))
            return KeysetHandle.newBuilder().addEntry(KeysetHandle.importKey(priv).withRandomId().makePrimary()).build()
        }

        fun hpkeFromRaw(privateKey: ByteArray, publicKey: ByteArray): KeysetHandle {
            val pub = HpkePublicKey.create(TinkKeys.hpkeParameters, Bytes.copyFrom(publicKey), null)
            val priv = HpkePrivateKey.create(pub, SecretBytes.copyFrom(privateKey, InsecureSecretKeyAccess.get()))
            return KeysetHandle.newBuilder().addEntry(KeysetHandle.importKey(priv).withRandomId().makePrimary()).build()
        }
    }
}
